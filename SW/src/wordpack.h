/*******************************************************************************
 * Project:     SeedMate
 * File:        wordpack.h
 *
 * Summary:
 *   Decoder of the packed word lists (BIP39 in words_opt.h, EFF in EFF_short.c).
 *
 * Description:
 *   The lists are kept whole, in their order, but packed to about 40% of plain
 *   text. Bits are read most significant first. Each word is:
 *     2 bits   how many first letters it shares with the previous word (0..3)
 *     5 bits   per remaining letter: 1..26 = a..z, 27 = '-'
 *     5 bits   0, the end of the word
 *   Every WORDLIST_BLOCK words the shared count is 0 and restart[] gives the bit
 *   where that word starts, so a word is found without decoding the whole list.
 *   Generated by test/words/pack_words.py; test/words/test_wordlists.c and
 *   test/eff/test_eff.c rebuild the official files and check their SHA-256.
 *
 *   The code is compiled once, in EFF_short.c (WORDPACK_IMPLEMENT).
 ******************************************************************************/

#ifndef WORDPACK_H
#define WORDPACK_H

#include <stdint.h>
#include <stdbool.h>
#include <stddef.h>

#define WORDLIST_BLOCK      128u        // Words between two restart points
#define WORDLIST_WORD_MAX   8           // Longest word of either list

typedef struct {
    const uint8_t *bits;
    const uint16_t *restart;            // Bit offset of each block
    uint16_t count;
} wordlist_t;

// Walks a list: after wordlist_next(), word holds word number index - 1
typedef struct {
    const wordlist_t *list;
    uint32_t bit;
    uint16_t index;
    char word[WORDLIST_WORD_MAX + 1];
} wordlist_iter_t;

// Positions it at the start of the block holding word 'index'
void wordlist_seek(wordlist_iter_t *it, const wordlist_t *list, uint32_t index);

// Positions it where the words starting with prefix can begin. Sorted lists only.
void wordlist_seek_prefix(wordlist_iter_t *it, const wordlist_t *list, const char *prefix, size_t len);

// Decodes the next word. False at the end of the list.
bool wordlist_next(wordlist_iter_t *it);

// Copies word 'index' to out (WORDLIST_WORD_MAX + 1 bytes)
void wordlist_get(const wordlist_t *list, uint32_t index, char *out);

// Index of a word, or -1. Sorted lists only.
int wordlist_find(const wordlist_t *list, const char *word);

#ifdef WORDPACK_IMPLEMENT
#include <string.h>
#include "memzero.h"

// The lists end with a spare byte, so reading the byte after the last is safe
static uint8_t read_bits(const uint8_t *p, uint32_t bit, uint8_t n) {
    uint32_t i = bit >> 3;
    uint32_t v = ((uint32_t)p[i] << 8) | p[i + 1];
    return (uint8_t)((v >> (16u - n - (bit & 7u))) & ((1u << n) - 1u));
}

void wordlist_seek(wordlist_iter_t *it, const wordlist_t *list, uint32_t index) {
    it->list = list;
    it->index = (uint16_t)(index & ~(WORDLIST_BLOCK - 1u));
    it->bit = list->restart[index / WORDLIST_BLOCK];
    it->word[0] = '\0';
}

bool wordlist_next(wordlist_iter_t *it) {
    const uint8_t *bits = it->list->bits;
    uint8_t n;

    if (it->index >= it->list->count) return false;
    n = read_bits(bits, it->bit, 2);
    it->bit += 2;
    for (;;) {
        uint8_t c = read_bits(bits, it->bit, 5);
        it->bit += 5;
        if (c == 0) break;
        if (n < WORDLIST_WORD_MAX) it->word[n++] = (c == 27) ? '-' : (char)('a' + c - 1);
    }
    it->word[n] = '\0';
    it->index++;
    return true;
}

void wordlist_seek_prefix(wordlist_iter_t *it, const wordlist_t *list, const char *prefix, size_t len) {
    uint32_t block = 0;
    // The last block whose first word is before the prefix
    while ((block + 1u) * WORDLIST_BLOCK < list->count) {
        wordlist_seek(it, list, (block + 1u) * WORDLIST_BLOCK);
        wordlist_next(it);
        if (strncmp(it->word, prefix, len) >= 0) break;
        block++;
    }
    wordlist_seek(it, list, block * WORDLIST_BLOCK);
}

void wordlist_get(const wordlist_t *list, uint32_t index, char *out) {
    wordlist_iter_t it;
    wordlist_seek(&it, list, index);
    while (it.index <= index && wordlist_next(&it)) { }
    strcpy(out, it.word);
    memzero(&it, sizeof(it));                   // It may be a word of a seed
}

int wordlist_find(const wordlist_t *list, const char *word) {
    wordlist_iter_t it;
    int found = -1;

    wordlist_seek_prefix(&it, list, word, strlen(word));
    while (wordlist_next(&it)) {
        int cmp = strcmp(it.word, word);
        if (cmp == 0) found = it.index - 1;
        if (cmp >= 0) break;
    }
    memzero(&it, sizeof(it));
    return found;
}
#endif // WORDPACK_IMPLEMENT

#endif // WORDPACK_H
