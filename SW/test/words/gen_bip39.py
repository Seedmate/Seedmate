#!/usr/bin/env python3
"""Writes ../../src/words_opt.h from the official BIP39 English word list.

Usage: python gen_bip39.py english.txt
The input is bip-0039/english.txt of the bitcoin/bips repository; the script
refuses any other content. test_wordlists.c then rebuilds the file from the
firmware's list and checks the same SHA-256.
"""
import hashlib
import os
import sys

from pack_words import BLOCK, c_tables, pack

OFFICIAL_SHA256 = '2f5eed53a4727b4bf8880d8f3f199efc90e58503646d9ff8eff3a2ed3b24dbda'

src = open(sys.argv[1], 'rb').read()
if hashlib.sha256(src).hexdigest() != OFFICIAL_SHA256:
    sys.exit('unexpected SHA-256')
words = src.decode('ascii').split()
assert len(words) == 2048 and words == sorted(words)

data, restart = pack(words)
text = ('/* Generated by test/words/gen_bip39.py from the official BIP39 English list. Do not edit by hand. */\n'
        '/* Packed as described in wordpack.h. */\n'
        '#ifndef WORDS_H\n#define WORDS_H\n\n#include "wordpack.h"\n\n' +
        c_tables('bip39', data, restart) +
        '\nstatic const wordlist_t bip39_list = {bip39_bits, bip39_restart, 2048};\n\n#endif\n')
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '../../src/words_opt.h'), 'w', newline='\n').write(text)
print('BIP39:', len(data), 'bytes,', len(restart), 'restart points, block', BLOCK)
