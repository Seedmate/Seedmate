#!/usr/bin/env python3
"""Writes ../../src/EFF_short.c from the official EFF Short Wordlist 1.

Usage: python gen_eff_short.py eff_short_wordlist_1.txt

The input is the file published by the EFF
(https://www.eff.org/files/2016/09/08/eff_short_wordlist_1.txt): 1296 lines
"dddd<TAB>word", dice numbers 1111..6666 in order. The script refuses any
other content; test_eff.c then checks that the firmware list rebuilds the
same file byte for byte (SHA-256).
"""
import hashlib
import itertools
import os
import sys

OFFICIAL_SHA256 = '8f5ca830b8bffb6fe39c9736c024a00a6a6411adb3f83a9be8bfeeb6e067ae69'

src = open(sys.argv[1], 'rb').read()
digest = hashlib.sha256(src).hexdigest()
if digest != OFFICIAL_SHA256:
    sys.exit('unexpected SHA-256 ' + digest)

lines = src.decode('ascii').split('\n')
assert lines[-1] == '' and len(lines) == 1297, 'expected 1296 lines'
words = []
for line, dice in zip(lines[:-1], itertools.product('123456', repeat=4)):
    num, word = line.split('\t')
    assert num == ''.join(dice), (num, dice)
    assert word and all(c.islower() or c == '-' for c in word), word
    words.append(word)
assert len(set(words)) == 1296

HEADER = '''/*******************************************************************************
 * Project:     SeedMate
 * File:        EFF_short.c
 *
 * Summary:
 *   EFF Short Wordlist 1 (1296 words, 4 dice per word) for EFF PASSWORD.
 *
 * Description:
 *   Generated by test/eff/gen_eff_short.py from the official file
 *   https://www.eff.org/files/2016/09/08/eff_short_wordlist_1.txt
 *   (SHA-256 %s). Do not edit by hand.
 *   The words are stored as one string with NUL separators (no pointer
 *   table), in dice order: index = (d1-1)*216 + (d2-1)*36 + (d3-1)*6 + (d4-1)
 *   for the dice 1111..6666. test/eff/test_eff.c rebuilds the official file
 *   from this list and checks its SHA-256.
 *
 *   Word list: Electronic Frontier Foundation, CC BY 3.0 US
 *   (https://www.eff.org/dice).
 ******************************************************************************/

#include <stddef.h>
#include "EFF_short.h"

const char eff_short_words[] =
''' % OFFICIAL_SHA256

FOOTER = ''';

// Word of a dice number (index 0..1295), NULL if out of range
const char *get_eff_short_word(int index) {
    if (index < 0 || index >= EFF_SHORT_WORDS) return NULL;
    const char *ptr = eff_short_words;
    for (int i = 0; i < index; i++) {
        while (*ptr != '\\0') ptr++;
        ptr++;
    }
    return ptr;
}
'''

out = [HEADER]
for i in range(0, len(words), 8):
    out.append('    "' + ''.join(w + '\\0' for w in words[i:i + 8]) + '"\n')
out[-1] = out[-1].rstrip('\n')
out.append(FOOTER)
path = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'src', 'EFF_short.c')
with open(path, 'w', newline='\r\n') as f:
    f.write(''.join(out))
print('wrote', os.path.normpath(path), len(words), 'words')
