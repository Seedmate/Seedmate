"""Copies the functions of ../../src/main.c that the backup HTML page must match
(obfuscations, card encoding, poker card bits, Shamir split) into backup_extract.inc,
so gen_backup_vectors.c computes the vectors with the firmware's own code."""
import re

SRC = '../../src/main.c'
OUT = 'backup_extract.inc'

# Whole functions or definitions, found by their first line and copied to the
# closing brace of their body (or the ';' of a table)
FUNCTIONS = [
    'const char * const card_entropy_map[52] = {',
    'void set_bit(BYTE data_array[36], int bit_index, int value) {',
    'static void write_11bit_value(BYTE *buffer, int index, int value) {',
    'void addsub_11bit_groups(size_t size, int amount, int add_sub) {',
    'static void shift_left(BYTE *data, int N)',
    'static void not_operator(BYTE *data, int N)',
    'static void byte_swap_pairs(BYTE *data, int N)',
    'static void shift_right(BYTE *data, int N)',
    'void apply_1word_xor(int word_idx, int size) {',
    'static void append_entropy_bits(const char *bits, size_t len) {',
]
# Regions copied as they are, start included, end excluded
REGIONS = [
    ('#define BEAM_WIDTH', '// Reads the CSD register'),
    ('#ifndef BS_LANES', '/* ===== Entropy extraction'),
]

text = open(SRC, encoding='utf-8').read().replace('\r\n', '\n')


def body(start):
    # The definition, not the prototype: the body follows the first line
    a = text.index(start)
    while not start.endswith('{') and text[a + len(start):].lstrip()[0] != '{':
        a = text.index(start, a + 1)
    i = text.index('{', a)
    depth = 0
    while True:
        c = text[i]
        if c == '{':
            depth += 1
        elif c == '}':
            depth -= 1
            if depth == 0:
                break
        i += 1
    end = i + 1
    if text[end] == ';':
        end += 1
    return text[a:end]


parts = [body(f) for f in FUNCTIONS]
for start, end in REGIONS:
    a = text.index(start)
    parts.append(text[a:text.index(end, a)])
out = '// Generated by extract_backup.py from src/main.c. Do not edit.\n\n' + '\n\n'.join(parts) + '\n'
# No screen code: the bench defines only the state these functions use
assert not re.search(r'\bprint_|\bdraw_|\btext_at\b', out), 'screen code in the extract'
open(OUT, 'w', encoding='utf-8', newline='\n').write(out)
print('wrote', OUT)
