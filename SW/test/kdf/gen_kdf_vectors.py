"""Writes kdf_vectors.h: HMAC-SHA512 and BIP39 PBKDF2 references for test_kdf.c.

Expected values come from Python's hashlib/hmac, which is independent from
the firmware code; the published vectors below check the script itself.
"""
import hashlib, hmac

def pbkdf2(mnemonic, passphrase):
    return hashlib.pbkdf2_hmac('sha512', mnemonic.encode(), ('mnemonic' + passphrase).encode(), 2048)

ABANDON12 = ' '.join(['abandon'] * 11 + ['about'])
ABANDON24 = ' '.join(['abandon'] * 23 + ['art'])

# Published vectors: RFC 4231 test cases 2 and 6, BIP39 (Trezor) vectors
assert hmac.new(b'Jefe', b'what do ya want for nothing?', hashlib.sha512).hexdigest() == (
    '164b7a7bfcf819e2e395fbe73b56e0a387bd64222e831fd610270cd7ea2505549758bf75c05a994a6d034f65f8f0e6fd'
    'caeab1a34d4a6b4b636e070a38bce737')
assert hmac.new(b'\xaa' * 131, b'Test Using Larger Than Block-Size Key - Hash Key First', hashlib.sha512).hexdigest() == (
    '80b24263c7c1a3ebb71493c1dd7be8b49b46d1f41b4aeec1121b013783f8f3526b56d037e05f2598bd0fd2215d6a1e52'
    '95e64f73f63f0aec8b915a985d786598')
assert pbkdf2(ABANDON12, '').hex() == (
    '5eb00bbddcf069084889a8ab9155568165f5c453ccb85e70811aaed6f6da5fc19a5ac40b389cd370d086206dec8aa6c4'
    '3daea6690f20ad3d8d48b2d2ce9e38e4')
assert pbkdf2(ABANDON12, 'TREZOR').hex() == (
    'c55257c360c07c72029aebc1b53c05ed0362ada38ead3e3e9efa3708e53495531f09a6987599d18264c1e1c92f2cf141'
    '630c7a3c4ab7c81b2f001698e7463b04')

# Passphrases around and far beyond the old 20-character limit (the device allows 199)
cases = [
    (ABANDON12, ''),
    (ABANDON12, 'TREZOR'),
    (ABANDON12, 'P' * 20),
    (ABANDON12, 'P' * 21),
    (ABANDON12, 'correct horse battery staple, but much longer!!'),
    (ABANDON12, ''.join(chr(33 + i % 94) for i in range(199))),
    (ABANDON24, 'A long passphrase on a 24-word mnemonic: 0123456789'),
]

def c_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

with open('kdf_vectors.h', 'w', newline='\r\n') as f:
    f.write('// Generated by gen_kdf_vectors.py (Python hashlib)\n#include <stdint.h>\n\n')
    f.write('typedef struct { const char *mnemonic; const char *passphrase; uint8_t seed[64]; } kdf_case_t;\n\n')
    f.write('static const kdf_case_t kdf_cases[] = {\n')
    for m, p in cases:
        seed = pbkdf2(m, p)
        f.write('    {%s,\n     %s,\n     {%s}},\n' % (c_str(m), c_str(p), ', '.join('0x%02x' % b for b in seed)))
    f.write('};\n\n')
    for name, key, msg in [('jefe', b'Jefe', b'what do ya want for nothing?'),
                           ('long_key', b'\xaa' * 131, b'Test Using Larger Than Block-Size Key - Hash Key First')]:
        mac = hmac.new(key, msg, hashlib.sha512).digest()
        f.write('static const uint8_t hmac_%s_mac[64] = {%s};\n' % (name, ', '.join('0x%02x' % b for b in mac)))
print('ok', len(cases), 'PBKDF2 cases')
