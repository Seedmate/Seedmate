"""Copies the entropy check of CREATE out of ../../src/main.c into check_extract.inc.

test_entropy_check.c includes that file, so the host test runs the firmware's
own entropy_check_ok() and its helpers, not a copy kept by hand.
"""
SRC = '../../src/main.c'
OUT = 'check_extract.inc'
START = '// Bits pos..pos+len-1 of the entropy as a number'
END = '// REDO: the entropy, the histories and the dice string go; back to the size menu'

text = open(SRC, encoding='utf-8').read().replace('\r\n', '\n')
a = text.index(START)
b = text.index(END, a)
open(OUT, 'w', encoding='utf-8', newline='\n').write(
    '// Generated by extract_check.py from src/main.c. Do not edit.\n\n' + text[a:b])
print('wrote', OUT)
