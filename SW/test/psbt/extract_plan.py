"""Copies the PSBT signing decision out of ../../src/main.c into plan_extract.inc.

test_malicious.c includes that file, so the host test runs the firmware's own
psbt_check_owner() and psbt_plan_signing(), not a copy kept by hand. main.c
cannot be compiled on a PC as a whole (registers, display, state machine).
"""
SRC = '../../src/main.c'
OUT = 'plan_extract.inc'

REGIONS = [
    ('// Who owns an input or output, checked against the loaded seed',
     '// Ownership line at y and, when there is one'),
    ('#define PSBT_CHANGE_LOOKAHEAD',
     '// Shows what leaves the wallet and asks for OK'),
]

text = open(SRC, encoding='utf-8').read().replace('\r\n', '\n')
parts = []
for start, end in REGIONS:
    a = text.index(start)
    b = text.index(end, a)
    parts.append(text[a:b])
open(OUT, 'w', encoding='utf-8', newline='\n').write(
    '// Generated by extract_plan.py from src/main.c. Do not edit.\n\n' + '\n'.join(parts))
print('wrote', OUT)
