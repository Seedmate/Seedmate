"""Nested segwit (BIP49, P2SH-P2WPKH) test data for the "abandon x11 about" seed.

Independent from the firmware: the BIP32, secp256k1, RFC6979 and BIP143 code
is the Python of sign_abandon.py. Writes:
  abandon nested.psbt  - unsigned PSBT for the device: one input at
                         m/49'/0'/0'/0/0 with its previous transaction, a send
                         to an external bc1q address and change at m/49'/0'/0'/1/0
  nested_vectors.h     - that PSBT, the same signed by this signer, and the key,
                         for test_sign.c (the firmware must sign byte-identically)
Also checks the address of m/49'/0'/0'/0/0 and prints the account ypub.
"""
import runpy, struct, base64

g = runpy.run_path('sign_abandon.py')
H, seed, derive, master_key, ckd_priv = g['H'], g['seed'], g['derive'], g['master_key'], g['ckd_priv']
point_mul, ser_pub, hash160, sha256, dsha = g['point_mul'], g['ser_pub'], g['hash160'], g['sha256'], g['dsha']
b58check, varint, kv, keypath = g['b58check'], g['varint'], g['kv'], g['keypath']
bip143_sighash, sign, verify, der, N = g['bip143_sighash'], g['sign'], g['verify'], g['der'], g['N']
read_maps, write_maps = g['read_maps'], g['write_maps']

ACC = [49 | H, H, H]
master_priv, _ = master_key(seed)
FP = hash160(ser_pub(point_mul(master_priv)))[:4]
assert FP.hex() == '73c5da0a'

def nested_script(pub):
    """redeem script OP_0 <hash160(pub)> and the P2SH output paying to it"""
    redeem = b'\x00\x14' + hash160(pub)
    return redeem, b'\xa9\x14' + hash160(redeem) + b'\x87'

def p2sh_address(spk):
    return b58check(b'\x05' + spk[2:22])

priv_in = derive(seed, ACC + [0, 0])
pub_in = ser_pub(point_mul(priv_in))
redeem_in, spk_in = nested_script(pub_in)
# Published address of this seed at m/49'/0'/0'/0/0 (Electrum / Sparrow / iancoleman)
assert p2sh_address(spk_in) == '37VucYSaXLCAsxYyAPfbSi9eh4iEcbShgf', p2sh_address(spk_in)

priv_change = derive(seed, ACC + [1, 0])
pub_change = ser_pub(point_mul(priv_change))
redeem_change, spk_change = nested_script(pub_change)

# Account ypub (version 0x049D7CB2), parent = m/49'/0'
k, c = master_key(seed)
for idx in ACC[:2]:
    k, c = ckd_priv(k, c, idx)
parent_fp = hash160(ser_pub(point_mul(k)))[:4]
k, c = ckd_priv(k, c, ACC[2])
ypub = b58check(struct.pack('>I', 0x049D7CB2) + bytes([3]) + parent_fp + struct.pack('>I', ACC[2]) +
                c + ser_pub(point_mul(k)))
xpub = b58check(struct.pack('>I', 0x0488B21E) + bytes([3]) + parent_fp + struct.pack('>I', ACC[2]) +
                c + ser_pub(point_mul(k)))

# Previous transaction: one output of 250,000 sats to our nested address
AMOUNT = 250000
prev_tx = (struct.pack('<I', 2) + b'\x01' + sha256(b'nested prev') + struct.pack('<I', 0) + b'\x00' +
           struct.pack('<I', 0xffffffff) + b'\x01' +
           struct.pack('<Q', AMOUNT) + varint(len(spk_in)) + spk_in + struct.pack('<I', 0))
prev_txid = dsha(prev_tx)

EXTERNAL = bytes.fromhex('0014751e76e8199196d454941c45d1b3a323f1433bd6')   # bc1q of m/84'/0'/0'/1/0
SEND, CHANGE = 150000, 98000                                                 # Fee 2,000 sats
tx = (struct.pack('<I', 2) + b'\x01' + prev_txid + struct.pack('<I', 0) + b'\x00' +
      struct.pack('<I', 0xfffffffd) + b'\x02' +
      struct.pack('<Q', SEND) + varint(len(EXTERNAL)) + EXTERNAL +
      struct.pack('<Q', CHANGE) + varint(len(spk_change)) + spk_change + struct.pack('<I', 870000))

in0 = (kv(b'\x00', prev_tx) +
       kv(b'\x01', struct.pack('<Q', AMOUNT) + varint(len(spk_in)) + spk_in) +
       kv(b'\x04', redeem_in) +
       kv(b'\x06' + pub_in, keypath(FP, *ACC, 0, 0)))
out_change = (kv(b'\x00', redeem_change) +
              kv(b'\x02' + pub_change, keypath(FP, *ACC, 1, 0)))
psbt = b'psbt\xff' + kv(b'\x00', tx) + b'\x00' + in0 + b'\x00' + b'\x00' + out_change + b'\x00'
maps = read_maps(psbt)
assert write_maps(maps) == psbt

# BIP143: the scriptCode of P2SH-P2WPKH is the P2PKH of the key hash
script_code = b'\x19\x76\xa9\x14' + hash160(pub_in) + b'\x88\xac'
sighash, _ = bip143_sighash(tx, 0, script_code, AMOUNT)
r, s = sign(priv_in, sighash)
assert verify(point_mul(priv_in), sighash, r, s) and s <= N // 2
sig = der(r, s) + b'\x01'
maps[1].append((b'\x02' + pub_in, sig))
signed = write_maps(maps)

open('abandon nested.psbt', 'wb').write(psbt)

def c_array(f, name, data):
    f.write('static const uint8_t %s[%d] = {\n' % (name, len(data)))
    for i in range(0, len(data), 16):
        f.write('    ' + ', '.join('0x%02x' % b for b in data[i:i + 16]) + ',\n')
    f.write('};\n\n')

with open('nested_vectors.h', 'w', newline='\r\n') as f:
    f.write('// Generated by test/psbt/gen_nested.py - test data only, not a secret.\n')
    f.write('// "abandon x11 about" P2SH-P2WPKH (BIP49) PSBT, signed by the independent Python signer.\n')
    f.write('#ifndef NESTED_VECTORS_H\n#define NESTED_VECTORS_H\n\n#include <stdint.h>\n\n')
    f.write('// Unsigned, and input 0 signed with m/49h/0h/0h/0/0\n')
    c_array(f, 'nested_psbt', psbt)
    c_array(f, 'nested_signed_psbt', signed)
    c_array(f, 'nested_priv_0_0', priv_in.to_bytes(32, 'big'))
    c_array(f, 'nested_pub_0_0', pub_in)
    f.write('#endif // NESTED_VECTORS_H\n')

print('receive 0 ', p2sh_address(spk_in))
print('change 0  ', p2sh_address(spk_change))
print('ypub      ', ypub)
print('xpub      ', xpub)
print('sighash   ', sighash.hex())
print('PSBT', len(psbt), 'bytes, signed', len(signed), 'bytes')
print('base64    ', base64.b64encode(psbt).decode())
