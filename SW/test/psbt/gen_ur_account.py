"""Writes ur_account_vectors.h: crypto-account (BCR-2020-015) references.

The CBOR is built with a generic encoder written from RFC 8949 and the
BCR-2020-007/010/015 specs, independent from ur_account_cbor() in C. Keys
come from the "abandon x11 about" seed with the BIP32 code of
sign_abandon.py (checked there against the BIP84 test vectors).
"""
import runpy, struct

g = runpy.run_path('sign_abandon.py')
H, seed, master_key, ckd_priv = g['H'], g['seed'], g['master_key'], g['ckd_priv']
point_mul, ser_pub, hash160 = g['point_mul'], g['ser_pub'], g['hash160']

class Tag:
    def __init__(self, tag, value):
        self.tag, self.value = tag, value

def cbor_head(major, n):
    if n < 24: return bytes([major << 5 | n])
    if n < 0x100: return bytes([major << 5 | 24, n])
    if n < 0x10000: return bytes([major << 5 | 25]) + struct.pack('>H', n)
    return bytes([major << 5 | 26]) + struct.pack('>I', n)

def cbor(v):
    if isinstance(v, bool): return b'\xf5' if v else b'\xf4'
    if isinstance(v, int): return cbor_head(0, v)
    if isinstance(v, bytes): return cbor_head(2, len(v)) + v
    if isinstance(v, list): return cbor_head(4, len(v)) + b''.join(cbor(x) for x in v)
    if isinstance(v, dict):         # Integer keys in ascending order (canonical)
        return cbor_head(5, len(v)) + b''.join(cbor(k) + cbor(v[k]) for k in sorted(v))
    if isinstance(v, Tag): return cbor_head(6, v.tag) + cbor(v.value)
    raise TypeError(v)

def account(path, multisig):
    """Public data of the account key at 'path' (list of indexes)."""
    k, c = master_key(seed)
    master_fp = hash160(ser_pub(point_mul(k)))[:4]
    parent_fp = None
    for idx in path:
        parent_fp = hash160(ser_pub(point_mul(k)))[:4]
        k, c = ckd_priv(k, c, idx)
    pub = ser_pub(point_mul(k))
    fp = int.from_bytes(master_fp, 'big')
    keypath = Tag(304, {1: [x for idx in path for x in (idx & ~H, bool(idx & H))], 2: fp})
    hdkey = Tag(303, {3: pub, 4: c, 6: keypath, 8: int.from_bytes(parent_fp, 'big')})
    script = Tag(401, Tag(410, hdkey)) if multisig else Tag(404, hdkey)
    return {
        'master_fp': fp, 'parent_fp': int.from_bytes(parent_fp, 'big'), 'pub': pub, 'chain': c,
        'path': path, 'multisig': multisig,
        'cbor': cbor({1: fp, 2: [Tag(308, script)]}),
    }

cases = [
    account([84 | H, 0 | H, 0 | H], False),
    account([84 | H, 0 | H, 5 | H], False),
    account([48 | H, 0 | H, 0 | H, 2 | H], True),
    account([48 | H, 0 | H, 255 | H, 2 | H], True),     # Largest account the device allows
]

def arr(name, data, fmt='0x%02x'):
    return 'static const uint8_t %s[%d] = {%s};\n' % (name, len(data), ', '.join(fmt % b for b in data))

with open('ur_account_vectors.h', 'w', newline='\r\n') as f:
    f.write('// Generated by gen_ur_account.py - test data only ("abandon x11 about" public keys)\n')
    f.write('#include <stdint.h>\n#include <stdbool.h>\n\n#define UR_ACCOUNT_CASES %d\n\n' % len(cases))
    for i, a in enumerate(cases):
        f.write(arr('acc%d_pub' % i, a['pub']))
        f.write(arr('acc%d_chain' % i, a['chain']))
        f.write(arr('acc%d_cbor' % i, a['cbor']))
        f.write('static const uint32_t acc%d_path[%d] = {%s};\n\n' % (i, len(a['path']), ', '.join('0x%08xu' % p for p in a['path'])))
    f.write('typedef struct { uint32_t master_fp, parent_fp; const uint8_t *pub, *chain, *cbor; uint32_t cbor_len;\n'
            '                 const uint32_t *path; uint8_t path_len; bool multisig; } ur_account_case_t;\n\n')
    f.write('static const ur_account_case_t ur_account_cases[UR_ACCOUNT_CASES] = {\n')
    for i, a in enumerate(cases):
        f.write('    {0x%08xu, 0x%08xu, acc%d_pub, acc%d_chain, acc%d_cbor, sizeof(acc%d_cbor), acc%d_path, %d, %s},\n'
                % (a['master_fp'], a['parent_fp'], i, i, i, i, i, len(a['path']), 'true' if a['multisig'] else 'false'))
    f.write('};\n')
for a in cases:
    print('path len %d multisig %-5s CBOR %d bytes' % (len(a['path']), a['multisig'], len(a['cbor'])))
