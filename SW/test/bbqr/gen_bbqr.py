"""BBQr test frames for test_bbqr.c (writes bbqr_vectors.h).

An independent BBQr encoder written from the spec (github.com/coinkite/BBQr,
BBQr.md): "B$" + encoding (H hex, 2 base32, Z raw deflate wbits 10 then
base32) + file type + total and index in two base 36 digits. Every part but
the last holds the same number of bytes. The files are the abandon test
PSBTs and descriptors of ../psbt (rule 5: test seeds only).

Run from this folder: python gen_bbqr.py
"""
import base64, zlib

PSBT_DIR = '../psbt/'
FILES = [
    ('P', 'abandon taproot.psbt'),
    ('P', 'abandon nested multisig.psbt'),
    ('U', 'MSDESC.TXT'),
    ('U', 'MSCOLD.TXT'),
]
B36 = '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ'


def b36(n):
    return B36[n // 36] + B36[n % 36]


def deflate(data, wbits):
    c = zlib.compressobj(9, zlib.DEFLATED, -wbits)
    return c.compress(data) + c.flush()


def frames(data, enc, ftype, max_chars):
    """Splits like a low density QR: at most max_chars per code. Also gives
    the number of bytes sent (compressed for Z)."""
    if enc == 'Z':
        data = deflate(data, 10)
    if enc == 'W':                      # Z with a 32 KB window: also inflates
        data, enc = deflate(data, 15), 'Z'
    room = max_chars - 8
    per = room // 2 if enc == 'H' else (room // 8) * 5     # base32: whole groups of 8 chars
    parts = [data[i:i + per] for i in range(0, len(data), per)] or [b'']
    out = []
    for i, p in enumerate(parts):
        txt = p.hex().upper() if enc == 'H' else base64.b32encode(p).decode().rstrip('=')
        out.append('B$' + enc + ftype + b36(len(parts)) + b36(i) + txt)
    return out, len(data)


# Near and over the 8,750 bytes a PSBT may take in the firmware buffer:
# repeated PSBT data with a pseudo random block, so it compresses partly
ms = open(PSBT_DIR + 'abandon nested multisig.psbt', 'rb').read()
rnd = bytes((i * 2654435761 >> 13) & 0xFF for i in range(1200))
SYNTH = {'big 8700': (ms * 6 + rnd)[:8700], 'over 9000': (ms * 6 + rnd)[:9000]}

cases = []
for ftype, name in FILES + [('P', 'big 8700'), ('P', 'over 9000')]:
    data = SYNTH[name] if name in SYNTH else open(PSBT_DIR + name, 'rb').read()
    sizes = (468,) if name in SYNTH else (468, 200, 4000)   # Low density (version 11), small parts, one code
    for enc in ('H', '2', 'Z', 'W'):
        for max_chars in sizes:
            fr, sent = frames(data, enc, ftype, max_chars)
            cases.append((name, ftype, enc, max_chars, data, fr, sent))

with open('bbqr_vectors.h', 'w', newline='\n') as f:
    f.write('// Generated by gen_bbqr.py. Do not edit.\n\n')
    names = []                          # Each file once, in hex
    for name, ftype, enc, mc, data, fr, sent in cases:
        if name not in names:
            f.write('static const char file%d_hex[] =\n' % len(names))
            hx = data.hex()
            for i in range(0, len(hx), 120):
                f.write('    "%s"\n' % hx[i:i + 120])
            f.write(';\n')
            names.append(name)
    for k, (name, ftype, enc, mc, data, fr, sent) in enumerate(cases):
        f.write('static const char *const case%d_frames[] = {\n' % k)
        for s in fr:
            f.write('    "%s",\n' % s)
        f.write('};\n')
    f.write('\nstatic const struct { const char *name; char type; char enc; int max_chars; '
            'const char *file_hex; unsigned file_len; unsigned sent_len; '
            'const char *const *frames; unsigned count; } cases[] = {\n')
    for k, (name, ftype, enc, mc, data, fr, sent) in enumerate(cases):
        f.write('    {"%s", \'%s\', \'%s\', %d, file%d_hex, %d, %d, case%d_frames, %d},\n'
                % (name, ftype, enc, mc, names.index(name), len(data), sent, k, len(fr)))
    f.write('};\n')
print('wrote bbqr_vectors.h,', len(cases), 'cases')
for name, ftype, enc, mc, data, fr, sent in cases:
    if mc == 468:
        print('  %-30s %s %5d bytes, %5d sent -> %2d parts' % (name, enc, len(data), sent, len(fr)))
