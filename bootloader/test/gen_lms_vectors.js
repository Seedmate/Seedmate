// Writes lms_vectors.h for test_boot_lms.c: signatures made by the signing page's
// own script (SW/tools/lms_sign.html), with the test words "abandon x11 about".
//   node gen_lms_vectors.js
"use strict";
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const html = fs.readFileSync(path.join(__dirname, "../../SW/tools/lms_sign.html"), "utf8");
const core = html.match(/<script id="core">([\s\S]*?)<\/script>/)[1];
const ctx = { TextDecoder, Uint8Array, Int32Array, Math, Array, Object, Number };
vm.createContext(ctx);
vm.runInContext(core + ";Object.assign(globalThis, { sha256, deriveKey, deriveC, buildTree, publicKey, lmsSign, PARAM_FIRMWARE });", ctx);
const { sha256, deriveKey, deriveC, buildTree, publicKey, lmsSign, PARAM_FIRMWARE } = ctx;

const table = (name, bytes) => {
  const rows = [];
  for (let i = 0; i < bytes.length; i += 16) {
    rows.push("    " + Array.from(bytes.subarray(i, i + 16), v => "0x" + v.toString(16).padStart(2, "0")).join(", "));
  }
  return "static const uint8_t " + name + "[" + bytes.length + "] = {\n" + rows.join(",\n") + "\n};\n";
};

(async () => {
  const key = deriveKey(new Uint8Array(16));
  const tree = await buildTree(key.id, key.seed, PARAM_FIRMWARE);
  const msg = sha256(new Uint8Array(Buffer.from(":020000040000FA\n:00000001FF\n")));
  let out = "// Generated by gen_lms_vectors.js. Test keys only.\n";
  out += table("vec_pub", publicKey(key.id, tree, PARAM_FIRMWARE));
  out += table("vec_msg", msg);
  for (const q of [0, 7, 1023]) {
    out += table("vec_sig_" + q, lmsSign(key.id, key.seed, tree, PARAM_FIRMWARE, q, deriveC(key.seed, q, msg), msg));
  }
  fs.writeFileSync(path.join(__dirname, "lms_vectors.h"), out);
  console.log("ok");
})();
